/** @lang zh-CN 仅为合成XML创建包装，不触及业务数据。 @lang en Wraps synthetic XML without touching target data. */
const xml = (assembly, ids) => `<doc><assembly><name>${assembly}</name></assembly><members>${ids.map(id=>`<member name="${id}"><summary>Summary</summary><remarks>Remarks</remarks></member>`).join('')}</members></doc>`;

it('selects the manual partial type declaration and records the selection', async () => {
  // <lang><zh-CN>临时合成项目故意让designer文件字典序靠前，检验非生成优先级。</zh-CN><en>The synthetic project puts the designer path first lexically to verify manual-source precedence.</en></lang>
  const root = await mkdtemp(path.join(tmpdir(),'dotnet-coverage-partial-'));
  await writeFile(path.join(root,'Sample.csproj'),'<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><AssemblyName>Sample</AssemblyName><TargetFramework>net8.0</TargetFramework></PropertyGroup></Project>');
  await writeFile(path.join(root,'A.designer.cs'),'// <auto-generated/>\nnamespace Demo; [System.CodeDom.Compiler.GeneratedCode("Test", "1")] public partial class Widget { public int Control; }');
  await writeFile(path.join(root,'Z.cs'),'namespace Demo; public partial class Widget { public void Run() {} }');
  await writeFile(path.join(root,'Sample.xml'),xml('Sample',['T:Demo.Widget','M:Demo.Widget.Run']));
  const out=path.join(root,'out');
  await runDotnetDoc({workspaceRoot:root,outputDirectory:out,inputs:[{kind:'dotnet-xml-doc',path:'Sample.xml',projectPath:'Sample.csproj'}],options:{writeSourceRelationArtifact:false}});
  const doc=JSON.parse(await readFile(path.join(out,'Sample.hia.json'),'utf8'));
  const type=doc.symbols.find(symbol=>symbol.kind==='dotnet-type');
  assert.equal(type.source?.definedIn.relativePath,'Z.cs');
  assert.equal(type.metadata.dotnetdoc.sourceLocationResolution.selectionRule,'non-generated-path-line');
  assert.equal(type.metadata.dotnetdoc.sourceLocationResolution.candidateCount,2);
  assert.equal(doc.metadata.sourceLocationResolution.resolved,2);
});

it('reports every unresolved member without adding unknown HIA root fields', async () => {
  const root=await mkdtemp(path.join(tmpdir(),'dotnet-coverage-diagnostics-'));
  await writeFile(path.join(root,'Sample.xml'),xml('Sample',['T:Demo.Missing','M:Demo.Missing.Run']));
  const out=path.join(root,'out');
  await runDotnetDoc({workspaceRoot:root,outputDirectory:out,inputs:[{kind:'dotnet-xml-doc',path:'Sample.xml'}]});
  const doc=JSON.parse(await readFile(path.join(out,'Sample.hia.json'),'utf8'));
  assert.equal(doc.sourceLocationResolution,undefined);
  assert.equal(doc.metadata.sourceLocationResolution.missing,2);
  for(const symbol of doc.symbols){
    const diagnostic=symbol.diagnostics.find(item=>item.code==='DOTNETDOC_SOURCE_LOCATION_MISSING');
    assert.equal(diagnostic?.data.symbolId,symbol.id);
    assert.equal(diagnostic?.data.reason,'missing');
    assert.equal(symbol.metadata.dotnetdoc.sourceLocationResolution.status,'missing');
  }
  assert.equal(doc.diagnostics.filter(item=>item.code==='DOTNETDOC_SOURCE_LOCATION_UNRESOLVED').length,1);
});

it('uses declared local assembly references for full overload and constructor identities', async () => {
  // <lang><zh-CN>只构建本测试新建的合成依赖；不执行任何业务项目MSBuild。</zh-CN><en>Build only this test's new synthetic dependency, never target-project MSBuild.</en></lang>
  const root=await mkdtemp(path.join(tmpdir(),'dotnet-coverage-references-'));
  await mkdir(path.join(root,'dep'));
  await mkdir(path.join(root,'app'));
  await writeFile(path.join(root,'dep','Types.csproj'),'<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net8.0</TargetFramework><AssemblyName>Types</AssemblyName></PropertyGroup></Project>');
  await writeFile(path.join(root,'dep','Types.cs'),'namespace Dependency; public class A {} public class B {}');
  await promisify(execFile)('dotnet',['build',path.join(root,'dep','Types.csproj'),'-o',path.join(root,'lib'),'-v','quiet'],{windowsHide:true});
  await writeFile(path.join(root,'app','App.csproj'),'<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net8.0</TargetFramework><AssemblyName>App</AssemblyName></PropertyGroup><ItemGroup><Reference Include="Types"><HintPath>../lib/Types.dll</HintPath></Reference></ItemGroup></Project>');
  await writeFile(path.join(root,'app','Widget.cs'),'using Dependency; namespace Demo; public class Widget { public Widget(A value) {} public Widget(B value) {} public void Run(A value) {} public void Run(B value) {} public void Run(ref A value) {} }');
  const artifact=await extractDotnetSourceFiles({workspaceRoot:root,projectPath:'app/App.csproj'});
  const ids=artifact.members.map(member=>member.semantic?.documentationCommentId);
  assert.ok(ids.includes('M:Demo.Widget.#ctor(Dependency.A)'));
  assert.ok(ids.includes('M:Demo.Widget.#ctor(Dependency.B)'));
  assert.ok(ids.includes('M:Demo.Widget.Run(Dependency.A)'));
  assert.ok(ids.includes('M:Demo.Widget.Run(Dependency.B)'));
  assert.ok(ids.includes('M:Demo.Widget.Run(Dependency.A@)'));
  assert.ok(artifact.source.projectContext.metadataReferenceCount>0);
  // <lang><zh-CN>ProjectReference同样优先使用XML旁已声明的copy-local副本，不执行被引用项目构建。</zh-CN><en>ProjectReference also prefers its declared XML-adjacent copy-local binary without building the referenced target.</en></lang>
  await writeFile(path.join(root,'app','App.csproj'),'<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net8.0</TargetFramework><AssemblyName>App</AssemblyName></PropertyGroup><ItemGroup><ProjectReference Include="../dep/Types.csproj" /></ItemGroup></Project>');
  const copyLocal=await extractDotnetSourceFiles({workspaceRoot:root,projectPath:'app/App.csproj',referenceDirectory:'lib'});
  assert.ok(copyLocal.members.some(member=>member.semantic?.documentationCommentId==='M:Demo.Widget.Run(Dependency.B)'));
});

/** @lang zh-CN 只构造定位事实，origin区分不同抽取/编译，不复制源码。 @lang en Constructs location facts only; origin separates extraction/compilation records without source bodies. */
function part(file,generated,origin,line=1){return {origin,assembly:'Sample',member:{kind:'dotnet-type',source:{path:file,range:{start:{line,column:1},end:{line:line+1,column:1}}},semantic:{documentationCommentId:'T:Demo.Widget',declaration:{isPartialType:true,declarationCount:2,isGenerated:generated}}}};}

it('orders proven partial declarations by manual source, path and line independently of input order',()=>{
  const origin={};
  const a=part('src/B.cs',false,origin),b=part('src/A.cs',false,origin);
  const select=items=>selectExactDeclaration({memberName:'T:Demo.Widget'},items,'Sample');
  assert.equal(select([a,b]).declaration,b.member);
  assert.equal(select([b,a]).declaration,b.member);
  const later=part('src/A.cs',false,origin,9);
  assert.equal(select([later,b]).declaration,b.member);
  const generated=part('src/A.designer.cs',true,origin);
  assert.equal(select([generated,a]).declaration,a.member);
});

it('keeps cross-extraction partials, duplicate registrations and non-partial conflicts ambiguous',()=>{
  const origin={};
  const a=part('src/A.cs',false,origin),b=part('src/B.cs',false,{});
  const select=items=>selectExactDeclaration({memberName:'T:Demo.Widget'},items,'Sample');
  assert.equal(select([a,b]).status,'ambiguous');
  assert.equal(select([a,a]).status,'ambiguous');
  b.origin=origin;b.member.semantic.declaration.isPartialType=false;
  assert.equal(select([a,b]).status,'ambiguous');
});

it('never promotes unresolved signature types to an exact identity',()=>{
  const candidate=part('src/A.cs',false,{});
  candidate.member.semantic.hasUnresolvedSignatureTypes=true;
  assert.equal(selectExactDeclaration({memberName:'T:Demo.Widget'},[candidate],'Sample').status,'missing');
});

it('bounds root diagnostics while retaining one reason per missing symbol',async()=>{
  const root=await mkdtemp(path.join(tmpdir(),'dotnet-coverage-many-'));
  await writeFile(path.join(root,'Sample.xml'),xml('Sample',Array.from({length:300},(_,index)=>`T:Demo.Missing${index}`)));
  const out=path.join(root,'out');
  const result=await runDotnetDoc({workspaceRoot:root,outputDirectory:out,inputs:[{kind:'dotnet-xml-doc',path:'Sample.xml'}]});
  const doc=JSON.parse(await readFile(path.join(out,'Sample.hia.json'),'utf8'));
  assert.equal(doc.metadata.sourceLocationResolution.missing,300);
  assert.equal(doc.diagnostics.length,1);
  assert.equal(result.diagnostics.length,1);
  assert.ok(doc.symbols.every(symbol=>symbol.diagnostics.length===1&&symbol.diagnostics[0].data.reason==='missing'));
});

it('does not read metadata symlinks escaping the workspace',async context=>{
  const root=await mkdtemp(path.join(tmpdir(),'dotnet-coverage-boundary-'));
  const outside=await mkdtemp(path.join(tmpdir(),'dotnet-coverage-outside-'));
  await writeFile(path.join(outside,'Private.dll'),'NOT_ALLOWED_METADATA_SENTINEL');
  try{await symlink(path.join(outside,'Private.dll'),path.join(root,'Reference.dll'),'file');}
  catch(error){if(error.code==='EPERM'){context.skip('Windows symlink privilege unavailable');return;}throw error;}
  await writeFile(path.join(root,'Sample.csproj'),'<Project><ItemGroup><Reference Include="Private"><HintPath>Reference.dll</HintPath></Reference></ItemGroup></Project>');
  const references=await resolveProjectMetadataReferences({workspaceRoot:root,projectPath:'Sample.csproj'});
  assert.deepEqual(references.paths,[]);
  assert.ok(references.diagnostics.some(diagnostic=>diagnostic.code==='DOTNETDOC_METADATA_REFERENCE_UNSAFE_OR_UNAVAILABLE'));
  assert.ok(!JSON.stringify(references).includes(outside));
});

it('refuses multiple project outputs when no same-build reference snapshot is supplied',async()=>{
  const root=await mkdtemp(path.join(tmpdir(),'dotnet-coverage-configurations-'));
  await mkdir(path.join(root,'debug'));await mkdir(path.join(root,'release'));
  await writeFile(path.join(root,'debug','Types.dll'),'DEBUG');
  await writeFile(path.join(root,'release','Types.dll'),'RELEASE');
  await writeFile(path.join(root,'Types.csproj'),'<Project><PropertyGroup><AssemblyName>Types</AssemblyName><OutputPath>debug</OutputPath></PropertyGroup><PropertyGroup><OutputPath>release</OutputPath></PropertyGroup></Project>');
  await writeFile(path.join(root,'App.csproj'),'<Project><ItemGroup><ProjectReference Include="Types.csproj" /></ItemGroup></Project>');
  const references=await resolveProjectMetadataReferences({workspaceRoot:root,projectPath:'App.csproj'});
  assert.deepEqual(references.paths,[]);
  assert.ok(references.diagnostics.some(diagnostic=>diagnostic.code==='DOTNETDOC_METADATA_REFERENCE_AMBIGUOUS'));
});

